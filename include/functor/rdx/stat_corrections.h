// Author: Alex Fernez
// MC stats should be reweighted to reflect a few things:
//   - it's useful to have equivalent polarity ratios for data/MC (if there are polarity-dependent effs,
//     then we get the wrong combination of events when putting together MU+MD for MC; this assumes that
//     the polarity-dependence of the effs is similar between MC and data)
//   - the muonic DDX dec files force a semimuonic decay, but in reality these proceed at different rates for D0, D+, Ds
//   - the produced "missing" modes (DstDK, DstDspi) weren't part of a DDX cocktail where the relative amounts were pre-adjusted, so along 
//     with the semimuonic BF for the specific D, they need to be corrected to reasonable amounts before combining with the other DDX

